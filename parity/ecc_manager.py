#!/usr/bin/env python3
"""
Simple 64-Bit Even & Odd Parity Checker Manager & Evaluator
===========================================================
Python Manager Script:
1. Generates 64-bit input test vectors and bit flip specifications -> 'input_vector.txt'.
2. Reads Verilog testbench simulation results -> 'output_vector.txt'.
3. Compares expected parity error detection against Verilog hardware outputs.

Note: Parity generation and error checking algorithms are executed EXCLUSIVELY 
in Verilog hardware modules (parity_check.v).
"""

import os
import random
import argparse

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
DEFAULT_INPUT_FILE = os.path.join(SCRIPT_DIR, "input_vector.txt")
DEFAULT_OUTPUT_FILE = os.path.join(SCRIPT_DIR, "output_vector.txt")

def generate_test_vectors(filename=DEFAULT_INPUT_FILE, num_cases=20):
    """Generates test cases for Verilog testbench simulation."""
    os.makedirs(os.path.dirname(os.path.abspath(filename)), exist_ok=True)
    test_cases = []

    # Sample 64-bit test patterns
    known_patterns = [
        0x0000000000000000,
        0xFFFFFFFFFFFFFFFF,
        0xAAAAAAAAAAAAAAAA,
        0x5555555555555555,
        0x123456789ABCDEF0,
        0xDEADBEEFCAFEFA00
    ]

    for data in known_patterns:
        # Even parity clean (flip 255: no flip)
        test_cases.append((data, 0, 255))
        # Even parity bit flip (0..63)
        test_cases.append((data, 0, random.randint(0, 63)))
        # Odd parity clean
        test_cases.append((data, 1, 255))
        # Odd parity bit flip
        test_cases.append((data, 1, random.randint(0, 63)))

    while len(test_cases) < num_cases:
        data = random.getrandbits(64)
        ptype = random.choice([0, 1])
        flip = random.choice([255, random.randint(0, 64)])
        test_cases.append((data, ptype, flip))

    with open(filename, "w") as f:
        for orig_data, ptype, flip_pos in test_cases:
            f.write(f"{orig_data:016X} {ptype} {flip_pos:3d}\n")

    print("=" * 75)
    print(f"[+] Generated {len(test_cases)} 64-bit test vectors in '{filename}'")
    print("=" * 75)

def evaluate_verilog_results(out_filename=DEFAULT_OUTPUT_FILE):
    """Parses output_vector.txt written by Verilog testbench and prints verification summary."""
    if not os.path.exists(out_filename):
        print(f"[-] Result file '{out_filename}' not found.")
        print(f"[-] Please run Verilog testbench 'tb_parity_check.v' to generate '{out_filename}'.")
        return False

    passed = 0
    failed = 0
    total = 0

    print("\n" + "=" * 80)
    print("             VERILOG 64-BIT PARITY CHECKER EVALUATION REPORT")
    print("=" * 80)
    print(f"{'CASE':<5} | {'ORIGINAL DATA':<18} | {'MODE':<6} | {'FLIP POS':<8} | {'ERR DETECTED':<12} | {'STATUS':<8}")
    print("-" * 80)

    with open(out_filename, "r") as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#"):
                continue

            parts = line.split()
            if len(parts) < 6:
                continue

            total += 1
            orig_data_hex = parts[0]
            ptype = int(parts[1])
            flip_pos = int(parts[2])
            gen_parity = int(parts[3])
            rx_parity = int(parts[4])
            err_detected = int(parts[5])

            mode_str = "EVEN" if ptype == 0 else "ODD"
            flip_str = f"Bit {flip_pos}" if flip_pos <= 64 else "NO FLIP"

            # Expected error state: flip_pos <= 64 means single bit error was injected
            expected_err = 1 if flip_pos <= 64 else 0
            case_passed = (err_detected == expected_err)

            if case_passed:
                passed += 1
                status = "PASS [OK]"
            else:
                failed += 1
                status = "FAIL [X]"

            print(f"{total:<5} | 0x{orig_data_hex:<16} | {mode_str:<6} | {flip_str:<8} | {err_detected:<12} | {status}")

    print("=" * 80)
    print(f"RESULTS: Total={total} | Passed={passed} | Failed={failed}")
    if failed == 0 and total > 0:
        print("[SUCCESS] All Verilog 64-bit parity checks succeeded perfectly!")
    print("=" * 80)
    return failed == 0

def main():
    parser = argparse.ArgumentParser(description="64-Bit Parity Checker Manager & Evaluator")
    parser.add_argument("--gen", action="store_true", help="Generate input test vectors")
    parser.add_argument("--evaluate", action="store_true", help="Evaluate output vector file generated by Verilog")
    parser.add_argument("--count", type=int, default=20, help="Number of test cases to generate")

    args = parser.parse_args()

    if args.gen:
        generate_test_vectors(num_cases=args.count)
    elif args.evaluate:
        evaluate_verilog_results()
    else:
        generate_test_vectors(num_cases=args.count)
        if os.path.exists(DEFAULT_OUTPUT_FILE):
            evaluate_verilog_results()

if __name__ == "__main__":
    main()
